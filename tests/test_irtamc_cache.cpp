// =============================================================================
// test_irtamc_cache — cache numerica gambit-coeffs (M-IRTAM-F2 P2, spec-hija).
//
// Test de logica pura: sin GL, sin red. Llama a PRODUCCION
// (namespace irtamccache en src/Data/IrtamCoeffCache.{h,cpp}), no replica.
// Valida contenido via P1a (parseMessage) — produccion real, no stub.
//
// Cubre F2 G4/G5: gate de escritura, round-trip bytes+sidecar, rechazo de
// contenido no-estructural, cap 96 POR PARAMETRO + self-heal + orden asc,
// coexistencia con tec_/kc2g_/irtam_. Patron test_kc2g_cache / test_irtam_cache.
// =============================================================================
#include "Data/IrtamCoeffCache.h"

#include <cstdio>
#include <cstring>
#include <filesystem>
#include <string>
#include <vector>

static int g_ok = 0, g_fail = 0;

static void check_bool(const char* what, bool cond) {
    if (cond) ++g_ok;
    else ++g_fail;
    std::printf("[%s] %s\n", cond ? "OK" : "FAIL", what);
}

static std::string freshDir(const char* tag) {
    namespace fs = std::filesystem;
    static int n = 0;
    std::string d = (fs::temp_directory_path() /
        ("irtamc_cache_test_" + std::string(tag) + "_" + std::to_string(n++))).string();
    fs::remove_all(d);
    return d;
}

// Mensaje 2x3 estructuralmente valido (~600 B).
static std::string miniMsg() {
    std::string m;
    m += "#START_HEADER\n";
    m += "# Generated by X on 2026-09-14T10:06:23Z\n";
    m += "# Ionospheric Characteristic: foF2 [MHz]\n";
    m += "# Time of Validity 2026-09-10T12:00:00.000Z\n";
    m += "# Assimilative Engine: NECTAR v0.2A\n";
    m += "# Earth Grid: 46 lats x 45 lons\n";
    m += "# Expansion Basis: JonesGallet_LinTrend\n";
    m += "# Basis Lengths: 2(temporal) x 3(spatial)\n";
    m += "# Assimilated stations:\n";
    m += "# AA343 AL945\n";
    m += "#END_HEADER\n";
    m += "  8.36785345  0.05910109 4.38351913e-02\n";
    m += " -2.22478358e-02 -1.31136373e-01  5.97193742e-02\n";
    return m;
}

static std::vector<uint8_t> bytesOf(const std::string& s) {
    return std::vector<uint8_t>(s.begin(), s.end());
}

int main() {
    using namespace irtamccache;

    std::printf("--- F2 P2: gate + frameName ---\n");
    {
        std::string mini = miniMsg();
        check_bool("mini >= 256 B", mini.size() >= 256);
        check_bool("gate acepta mini",
                   shouldCacheBucket(mini.size()));
        check_bool("gate rechaza 100 B", !shouldCacheBucket(100));
        check_bool("gate rechaza > 1 MB",
                   !shouldCacheBucket(2u * 1024u * 1024u));
        check_bool("nombre irtamc_<param>_<epoch>.txt",
                   frameName("hmF2", 1000.0) == "irtamc_hmf2_1000.txt");
        std::string d = freshDir("dir");
        check_bool("ensureDir crea", ensureDir(d) && std::filesystem::is_directory(d));
    }

    std::printf("--- F2 P2: round-trip bucket + sidecar ---\n");
    {
        std::string d = freshDir("rt");
        std::vector<uint8_t> g = bytesOf(miniMsg());
        const std::string lm("Mon, 10 Aug 2026 16:08:59 GMT");
        check_bool("save ok",
                   saveBucket(d, "foF2", 1789000000.0, g.data(), g.size(), lm));
        Bucket b;
        check_bool("load ok",
                   loadBucket(d + "/irtamc_fof2_1789000000.txt", b));
        check_bool("bytes bit-exactos", b.bytes == g);
        check_bool("lastmod del sidecar", b.serverLastMod == lm);
        check_bool("nCoeffs 6", b.nCoeffs == 6);
        check_bool("tovEpoch > 0", b.tovEpoch > 0.0);
        std::filesystem::remove(d + "/irtamc_fof2_1789000000.txt.meta");
        check_bool("load sin meta ok",
                   loadBucket(d + "/irtamc_fof2_1789000000.txt", b));
        check_bool("lastmod vacio sin meta", b.serverLastMod.empty());
        std::vector<uint8_t> bad = bytesOf(" 1.0 2.0\n");  // sin header
        check_bool("save rechaza no-estructural",
                   !saveBucket(d, "foF2", 1789000001.0, bad.data(), bad.size(), lm));
        std::string wrong = miniMsg() + " 9.9\n";  // 7 tokens vs 2x3
        std::vector<uint8_t> w = bytesOf(wrong);
        check_bool("save rechaza cuenta mala",
                   !saveBucket(d, "foF2", 1789000002.0, w.data(), w.size(), lm));
        check_bool("save rechaza epoch<=0",
                   !saveBucket(d, "foF2", 0.0, g.data(), g.size(), lm));
        std::string big(200, 'x');
        check_bool("save rechaza lastmod>128",
                   !saveBucket(d, "foF2", 1789000003.0, g.data(), g.size(), big));
    }

    std::printf("--- F2 P2: cap 96/param + heal + orden + coexistencia ---\n");
    {
        std::string d = freshDir("cap");
        std::vector<uint8_t> g = bytesOf(miniMsg());
        for (int i = 0; i < 98; i++)
            saveBucket(d, "foF2", 1000000.0 + i * 900.0, g.data(), g.size(),
                       "lm");
        for (int j = 0; j < 3; j++)
            saveBucket(d, "hmF2", 1000005.0 + j * 900.0, g.data(), g.size(),
                       "lm");
        FILE* fp = std::fopen((d + "/irtamc_fof2_9.txt").c_str(), "wb");
        std::fputs("GARBAGE", fp);
        std::fclose(fp);
        // Las otras 3 familias conviven en el mismo dir y no se tocan
        fp = std::fopen((d + "/tec_123.bin").c_str(), "wb");
        std::fputs("NOT-MINE", fp);
        std::fclose(fp);
        fp = std::fopen((d + "/kc2g_456.bin").c_str(), "wb");
        std::fputs("NOT-MINE", fp);
        std::fclose(fp);
        fp = std::fopen((d + "/irtam_fof2_789.gif").c_str(), "wb");
        std::fputs("GIF89a", fp);
        std::fclose(fp);
        fp = std::fopen((d + "/irtam_fof2_789.gif.meta").c_str(), "wb");
        std::fputs("lastmod=x", fp);
        std::fclose(fp);
        ScanResult r = loadCached(d);
        check_bool("96+3 kept", (int)r.buckets.size() == 99);
        check_bool("2 podados (fof2)", r.pruned == 2);
        check_bool("1 corrupto dropeado", r.dropped == 1);
        check_bool("corrupto borrado",
                   !std::filesystem::exists(d + "/irtamc_fof2_9.txt"));
        check_bool("ajenos intactos",
                   std::filesystem::exists(d + "/tec_123.bin") &&
                   std::filesystem::exists(d + "/kc2g_456.bin") &&
                   std::filesystem::exists(d + "/irtam_fof2_789.gif") &&
                   std::filesystem::exists(d + "/irtam_fof2_789.gif.meta"));
        bool sorted = true;
        for (size_t i = 1; i < r.buckets.size(); i++)
            if (r.buckets[i].epoch < r.buckets[i - 1].epoch) sorted = false;
        check_bool("orden asc por epoch", sorted);
        check_bool("front = hmf2 mas vieja",
                   r.buckets.front().epoch == 1000005.0);
        check_bool("fof2 conserva desde i=2",
                   r.buckets[2].epoch == 1000000.0 + 2 * 900.0);
        check_bool("param parseado", r.buckets.front().param == "hmf2");
        check_bool("meta en sweep",
                   r.buckets.front().serverLastMod == "lm");
    }

    std::printf("\n[test_irtamc_cache] %d OK, %d FAIL\n", g_ok, g_fail);
    return g_fail == 0 ? 0 : 1;
}
