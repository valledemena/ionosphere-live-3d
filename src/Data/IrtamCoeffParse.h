// M-IRTAM-F2 (P1a): parse del mensaje IRTAM Coefficients (gambit-coeffs).
//
// Modulo PURO: solo std (string/vector/cmath/cstdint). Sin curl, sin GL,
// sin App. Testeable en CI (tests/test_irtam_coeff_parse.cpp).
//
// Contrato P1a→P1b CONGELADO (ruling GLM F2-R1): este modulo extrae el header
// (ecos) + los coeficientes CRUDOS sin interpretar su orden. La evaluacion de
// la base Jones-Gallet a la malla 46x45 es P1b (port del reader FORTRAN).
// Sanity ESTRUCTURAL aqui (100% numerico, cuenta == nT*nS, finitud, ecos);
// el sanity FISICO (rangos MHz/km, esquinas E2) vive en P1b sobre la malla.
//
// Formato (PDF GAMBIT_CoefficientsMessageFormat.pdf; el fixture vivo GANA en
// conflicto): cabecera "#START_HEADER" ... "#END_HEADER", cuerpo con 4
// tokens/linea en F16.8 o notacion cientifica (deriva observada del servlet).
// =============================================================================
#include <cstdint>
#include <string>
#include <vector>

namespace irtamcoeff {

// Nombres declarados para el fold (grep): irtamcoeff::Header,
// irtamcoeff::Message, irtamcoeff::parseMessage, irtamcoeff::isStandardBasis.

struct Header {
    std::string characteristic;  // eco: "foF2" (primer token tras el ':')
    double tovEpoch = 0.0;       // eco: Time of Validity, segundos UTC
    int nTemporal = 0;           // eco validado: 14 en standard
    int nSpatial = 0;            // eco validado: 76 en standard
    int nLats = 0;               // informativo: 46 en Earth Grid
    int nLons = 0;               // informativo: 45 en Earth Grid
    std::string engine;          // informativo: "NECTAR ..."
    std::string generatedUtc;    // informativo: "Generated by ... on <iso>"
    int stationCount = 0;        // informativo: tokens tras Assimilated stations
};

struct Message {
    Header header;
    std::vector<double> coeffs;  // crudos, orden SIN interpretar (lo fija P1b)
    bool valid = false;
};

// Standard = lo que sirve el portal hoy: 14 x 76 + JonesGallet_LinTrend.
// Legacy (13 x 76, solo MasterApp) parsea pero NO es standard.
bool isStandardBasis(const Header& h);

// Parse + sanity estructural. Nunca lanza; a la salida `err` trae el motivo
// corto del rechazo (fail-soft por mensaje: un bucket corrupto no tira la capa).
bool parseMessage(const std::string& text, Message& out, std::string& err);

// Utilidad expuesta para tests: ISO-8601 "YYYY-MM-DDTHH:MM:SS[.frac](Z|±hh:mm)"
// -> segundos UTC. epoch 1970-01-01T00:00:00Z == 0.
bool parseIsoUtc(const std::string& iso, double& epochOut);

}  // namespace irtamcoeff
